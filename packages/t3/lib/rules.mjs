const escapeRegExp = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/**
 * One edit that fits each shape upstream's code has had, so a rule keeps
 * applying to the pinned release and to newer ones: exactly one of
 * `alternatives` ({ find, replace }, both text) must match, once, and gets its
 * own replacement. None, or two, is drift like any other anchor.
 */
const shapes = (...alternatives) => ({
  find: new RegExp(alternatives.map(({ find }) => `(${escapeRegExp(find)})`).join("|")),
  replace: (_, ...groups) => alternatives[groups.findIndex((group) => group !== undefined)].replace,
  alternatives,
});

/**
 * An edit for code a later upstream release added. Absence is never inferred
 * from what a file lacks (a rename or a move would read as "not added yet"):
 * the edit matches nowhere only in a file byte for byte as an audited release
 * from before that code shipped it, and exactly once in every other file.
 * `before` maps each such release to the sha-256 of upstream's file there
 * (lib/strip-engine.mjs absentIn, taken before any rule writes the file).
 */
const addedAfter = (before, edit) => ({ ...edit, absentIn: [...new Set(Object.values(before))], before });

/**
 * An edit for code only some audited releases ship (added, then removed again):
 * it matches once in a file byte for byte as one of those, and nowhere else.
 * `shippedIn` maps each such release to the sha-256 of upstream's file there.
 */
const shippedOnlyIn = (shippedIn, edit) => ({ ...edit, onlyIn: [...new Set(Object.values(shippedIn))], shippedIn });

